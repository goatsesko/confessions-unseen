CREATE POLICY "like a comment" ON public.comment_likes FOR INSERT TO authenticated WITH CHECK (auth.uid() = user_id);
CREATE POLICY "unlike a comment" ON public.comment_likes FOR DELETE TO authenticated USING (auth.uid() = user_id);

